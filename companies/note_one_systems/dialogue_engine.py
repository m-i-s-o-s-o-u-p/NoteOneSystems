    def get_random_grumble(self, emp_id: str, lang: str = "ja") -> dict:
        """
        10 x 10 x 10 x 10 = 10,000通り以上のユニークな愚痴を生成。
        """
        emp_cfg = self.grumble_templates.get(emp_id)
        if not emp_cfg:
            return {
                "text": "「チームの皆さんの背中を追いかけて、全力で業務をサポートしています！早く一人前になって貢献したいです。」",
                "target": "社内業務・チーム連携",
                "action": "サポート業務の進行",
                "impact": "成長痛とやりがいを感じています",
                "ending": "…今日も全力で頑張ります！",
                "combination_id": 1001,
                "total_variations": 10000
            }
        
        t_idx = random.randint(0, len(emp_cfg["targets"]) - 1)
        a_idx = random.randint(0, len(emp_cfg["actions"]) - 1)
        i_idx = random.randint(0, len(emp_cfg["impacts"]) - 1)
        e_idx = random.randint(0, len(emp_cfg["endings"]) - 1)

        t = emp_cfg["targets"][t_idx]
        a = emp_cfg["actions"][a_idx]
        i = emp_cfg["impacts"][i_idx]
        e = emp_cfg["endings"][e_idx]

        full_text = f"「{t}{a}{i}{e}」"
        comb_id = t_idx * 1000 + a_idx * 100 + i_idx * 10 + e_idx

        return {
            "text": full_text,
            "target": t.replace("、", "").replace("（", " ").replace("）", ""),
            "action": a,
            "impact": i,
            "ending": e,
            "combination_id": comb_id,
            "total_variations": len(emp_cfg["targets"]) * len(emp_cfg["actions"]) * len(emp_cfg["impacts"]) * len(emp_cfg["endings"])
        }

    def get_all_combinations_count(self) -> dict:
        """各社員の総組み合わせ数を返す（すべて10,000通り以上）"""
        res = {}
        for emp_id, cfg in self.grumble_templates.items():
            total = len(cfg["targets"]) * len(cfg["actions"]) * len(cfg["impacts"]) * len(cfg["endings"])
            res[emp_id] = total
        return res

